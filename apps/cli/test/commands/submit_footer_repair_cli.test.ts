import { expect } from 'chai';
import fs from 'fs';
import path from 'path';
import { getTestCliCommand } from '../../src/lib/utils/test_cli_command';
import { SubmitCliFixture } from '../lib/fixtures/submit_cli';

// Independent public CLI scenarios, not one production operation.
// eslint-disable-next-line max-lines-per-function
describe('submit dependency footer repair through the public CLI', function () {
  this.timeout(120000);
  let fixture: SubmitCliFixture;
  beforeEach(() => {
    fixture = new SubmitCliFixture();
  });
  afterEach(() => fixture.cleanup());

  it('does not repair cached footers when GitHub integration is disabled', () => {
    fixture.branch('base', 'main');
    fixture.succeed('submit');
    fixture.setPrs(
      fixture.prs().map((pr) => ({ ...pr, body: `Approved core${pr.body}` }))
    );
    fixture.succeed('repo', 'github', '--no-enable');
    const before = fixture.prs();
    fixture.clearCalls();

    fixture.succeed('submit');

    expect(fixture.prs()).to.deep.equal(before);
    expect(fixture.calls()).to.deep.equal([]);
  });

  it('leaves a matching footer and later bot content unchanged', () => {
    fixture.branch('base', 'main');
    fixture.succeed('submit');
    fixture.setPrs(
      fixture.prs().map((pr) => ({ ...pr, body: `${pr.body}\n\nBot summary` }))
    );
    const before = fixture.prs();
    fixture.clearCalls();

    fixture.succeed('submit');

    expect(fixture.prs()).to.deep.equal(before);
    expect(
      fixture
        .calls()
        .filter((call) => ['create', 'edit', 'ready'].includes(call[1]))
    ).to.deep.equal([]);
  });

  it('discloses footer-only repair in dry-run without editing the PR', () => {
    fixture.branch('base', 'main');
    fixture.succeed('submit');
    fixture.setPrs(
      fixture.prs().map((pr) => ({ ...pr, body: 'Approved core' }))
    );
    const before = fixture.prs();
    const remote = fixture.git('ls-remote', '--heads', 'origin');
    fixture.clearCalls();

    const output = fixture.succeed('submit', '--dry-run');

    expect(output).to.include('Dependency footers to repair: base (#1)');
    expect(fixture.prs()).to.deep.equal(before);
    expect(fixture.git('ls-remote', '--heads', 'origin')).to.equal(remote);
    expect(
      fixture
        .calls()
        .filter((call) => ['create', 'edit', 'ready'].includes(call[1]))
    ).to.deep.equal([]);
  });

  it('repairs stale and missing footers without code changes, then makes no redundant PR edits', () => {
    fixture.branch('base', 'main');
    fixture.branch('child', 'base');
    const initial = fixture.succeed('submit', '--stack');
    expect(initial).to.include('Pushing to remote');
    const expected = fixture.prs();
    fixture.setPrs(
      expected.map((pr) => ({
        ...pr,
        body:
          pr.headRefName === 'base'
            ? 'Approved base description\n\n\n#### PR Dependency Tree\n\n\n* **PR #1** 👈\n\nThis tree was auto-generated by [Anthracite](https://github.com/danielbaars/anthracite)'
            : 'Approved child description',
      }))
    );
    const refs = fixture.git('show-ref', '--heads');
    const remote = fixture.git('ls-remote', '--heads', 'origin');
    fixture.clearCalls();

    const output = fixture.succeed('submit', '--stack');
    expect(output).not.to.include('Pushing to remote');

    expect(fixture.prs().map((pr) => pr.body)).to.deep.equal(
      expected.map((pr) => `Approved ${pr.headRefName} description${pr.body}`)
    );
    expect(fixture.git('show-ref', '--heads')).to.equal(refs);
    expect(fixture.git('ls-remote', '--heads', 'origin')).to.equal(remote);
    expect(
      fixture
        .calls()
        .filter((call) => call[1] === 'edit' && call.includes('--body'))
    ).to.have.length(2);
    fixture.clearCalls();
    fixture.succeed('submit', '--stack');
    expect(
      fixture
        .calls()
        .filter((call) => ['create', 'edit', 'ready'].includes(call[1]))
    ).to.deep.equal([]);
  });

  it('reports the failed and unattempted footers after partial progress and repairs them on retry', () => {
    fixture.branch('base', 'main');
    fixture.branch('child', 'base');
    fixture.branch('tip', 'child');
    fixture.env.ANTHRACITE_TEST_GH_BODY_FAILURE_HEAD = 'child';

    const result = fixture.cli('submit', '--stack');

    expect(result.status).not.to.equal(0);
    expect(fixture.prs().map((pr) => pr.body.includes('PR #3'))).to.deep.equal([
      true,
      false,
      false,
    ]);
    const output = result.stdout + result.stderr;
    expect(output).to.include('Dependency footer update failed for child (#2)');
    expect(output).to.include(
      'Unconfirmed or stale dependency footers: child (#2), tip (#3)'
    );
    expect(output).not.to.include(
      'Unconfirmed or stale dependency footers: base'
    );
    delete fixture.env.ANTHRACITE_TEST_GH_BODY_FAILURE_HEAD;
    fixture.clearCalls();
    fixture.succeed('submit', '--stack');
    expect(fixture.prs().every((pr) => pr.body.includes('PR #3'))).to.equal(
      true
    );
    expect(
      fixture
        .calls()
        .filter((call) => call[1] === 'edit' && call.includes('--body'))
        .map((call) => call[2])
    ).to.deep.equal(['2', '3']);
  });

  it('reports pending footers when a later branch is frozen during an earlier footer edit', () => {
    fixture.branch('base', 'main');
    fixture.branch('child', 'base');
    fixture.branch('tip', 'child');
    fixture.succeed('submit', '--stack');
    fixture.setPrs(
      fixture.prs().map((pr) => ({ ...pr, body: 'Approved core' }))
    );
    const shim = path.join(fixture.root, 'bin', 'gh');
    const original = shim + '-original';
    fs.renameSync(shim, original);
    const freeze = getTestCliCommand(['freeze', 'child', '--no-interactive']);
    fs.writeFileSync(
      shim,
      `#!${process.execPath}
const cp = require('child_process');
const args = process.argv.slice(2);
const result = cp.spawnSync(${JSON.stringify(
        original
      )}, args, {encoding: 'utf8'});
process.stdout.write(result.stdout);
process.stderr.write(result.stderr);
if (result.status === 0 && args[0] === 'pr' && args[1] === 'edit' && args[2] === '1' && args.includes('--body')) {
  const frozen = cp.spawnSync(${JSON.stringify(freeze[0])}, ${JSON.stringify(
        freeze.slice(1)
      )}, {encoding: 'utf8'});
  if (frozen.status !== 0) throw new Error(frozen.stdout + frozen.stderr);
}
process.exitCode = result.status ?? 1;
`
    );
    fs.chmodSync(shim, 0o755);

    const result = fixture.cli('submit', '--stack');

    expect(result.status).not.to.equal(0);
    expect(result.stdout + result.stderr)
      .to.include('Cannot modify frozen branch')
      .and.include(
        'Unconfirmed or stale dependency footers: child (#2), tip (#3)'
      );
    expect(fixture.prs().map((pr) => pr.body.includes('PR #3'))).to.deep.equal([
      true,
      false,
      false,
    ]);
  });
});
